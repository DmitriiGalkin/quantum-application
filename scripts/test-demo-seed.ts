import mysql from 'mysql2/promise';
import { randomBytes } from 'node:crypto';
import { readFile } from 'node:fs/promises';
import assert from 'node:assert/strict';
import { DemoSeedService } from '../src/services/demo-seed.service.js';
import { DEMO_SEED_KEY } from '../src/services/demo-seed.data.js';
import { demoImageKeys } from '../src/services/demo-seed-assets.service.js';
import { DemoExtensionService } from '../src/services/demo-extension.service.js';
import { extensionIdeas } from '../src/services/demo-extension.data.js';
import { DemoMaintenanceService, personalSeedKey } from '../src/services/demo-maintenance.service.js';
import { PersonalDemoService } from '../src/services/demo-personal.service.js';
import IdeaRepository from '../src/repositories/idea.repository.js';
import { db } from '../src/utils/dbNext.js';

// Explicit isolated server only: never loads application .env or drops an existing database.
const database = `quantum_demo_test_${randomBytes(6).toString('hex')}`;
const pool = mysql.createPool({ host: '127.0.0.1', port: Number(process.env.DEMO_TEST_DB_PORT ?? 33079), user: process.env.DEMO_TEST_DB_USER ?? 'root', password: process.env.DEMO_TEST_DB_PASSWORD ?? '', connectionLimit: 1, multipleStatements: false, timezone: '+03:00' });
const conn = await pool.getConnection();
try {
  await conn.query(`CREATE DATABASE ${database} CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci`);
  await conn.query(`USE ${database}`);
  await conn.query("SET time_zone = '+03:00'");
  const schema = await readFile(new URL('../database-schema.md', import.meta.url), 'utf8');
  for (const match of schema.matchAll(/```sql\s+(CREATE TABLE[\s\S]*?)\s+```/g)) {
    await conn.query(match[1].replaceAll('utf8mb4_0900_ai_ci', 'utf8mb4_unicode_ci'));
  }
  await conn.query((await readFile(new URL('../migrations/003-demo-seed.sql', import.meta.url), 'utf8')).replaceAll('utf8mb4_0900_ai_ci', 'utf8mb4_unicode_ci'));
  for (let index = 1; index <= 4; index++) await conn.execute('INSERT INTO idea (title,description,catalogId,image) VALUES (?, ?, ?, ?)', [`Catalog ${index}`, 'Unknown manufacturing parameters retained', `toy-00${index}`, `https://storage.yandexcloud.net/quantum-education/catalog-${index}.jpg`]);
  const images = Object.fromEntries(demoImageKeys.map(key => [key, `https://storage.yandexcloud.net/quantum-education/demo/${DEMO_SEED_KEY}/${key}.jpg`]));
  const now = new Date('2030-01-01T12:00:00Z');
  const broken = { ...images };
  delete broken.lantern;
  await assert.rejects(DemoSeedService.seed(conn, broken, now), /Missing demo S3 image/);
  assert.equal((await DemoSeedService.inspect(conn)).records.length, 0);
  const [originals] = await conn.query<mysql.RowDataPacket[]>('SELECT * FROM idea ORDER BY id');
  const first = await DemoSeedService.seed(conn, images, now);
  assert.deepEqual(first.counts, { passport: 22, user: 24, place: 4, placePassport: 13, placeSchedule: 28, idea: 12, project: 18, projectUser: 105, meet: 40, meetUser: 140 });
  const ids = (await DemoSeedService.inspect(conn)).records;
  await DemoSeedService.seed(conn, images, new Date('2030-01-02T12:00:00Z'));
  assert.deepEqual((await DemoSeedService.inspect(conn)).records, ids);
  const [overlap] = await conn.query<mysql.RowDataPacket[]>("SELECT COUNT(*) AS count FROM meet a JOIN meet b ON a.id < b.id AND (a.passportId = b.passportId OR a.placeId = b.placeId) AND a.startedAt < DATE_ADD(b.startedAt, INTERVAL b.duration MINUTE) AND b.startedAt < DATE_ADD(a.startedAt, INTERVAL a.duration MINUTE)");
  assert.equal(overlap[0].count, 0);
  const extensionImages = Object.fromEntries(extensionIdeas.map(row => [row.key, `https://storage.yandexcloud.net/quantum-education/demo/${DEMO_SEED_KEY}/extension/${row.key}.jpg`]));
  await conn.beginTransaction();
  const extension = await DemoExtensionService.apply(conn, extensionImages, now);
  assert.equal(extension.counts.idea, 10);
  assert.equal(extension.counts.project, 15);
  assert.equal(extension.counts.meet, 33);
  await conn.rollback();
  assert.deepEqual((await DemoSeedService.inspect(conn)).records, ids);
  await conn.beginTransaction();
  await DemoExtensionService.apply(conn, extensionImages, now);
  await conn.commit();
  const extended = (await DemoSeedService.inspect(conn)).records;
  await conn.beginTransaction();
  assert.equal((await DemoExtensionService.apply(conn, {}, now)).alreadyPresent, true);
  await conn.commit();
  assert.deepEqual((await DemoSeedService.inspect(conn)).records, extended);
  const [extensionOverlap] = await conn.query<mysql.RowDataPacket[]>("SELECT COUNT(*) AS count FROM meet a JOIN meet b ON a.id < b.id AND (a.passportId = b.passportId OR a.placeId = b.placeId OR EXISTS (SELECT 1 FROM meetUser x JOIN meetUser y ON x.userId = y.userId WHERE x.meetId = a.id AND y.meetId = b.id)) AND a.startedAt < DATE_ADD(b.startedAt, INTERVAL b.duration MINUTE) AND b.startedAt < DATE_ADD(a.startedAt, INTERVAL a.duration MINUTE)");
  assert.equal(extensionOverlap[0].count, 0);
  const meetingId = ids.find(row => row.entityType === 'meet')!.recordId;
  await conn.execute('INSERT INTO meetUser (meetId,userId) VALUES (?, ?)', [meetingId, 99999]);
  await assert.rejects(DemoSeedService.removeData(conn), /external references/);
  assert.deepEqual((await DemoSeedService.inspect(conn)).records, extended);
  await conn.execute('DELETE FROM meetUser WHERE userId = ?', [99999]);
  await DemoSeedService.removeData(conn);
  assert.equal((await DemoSeedService.inspect(conn)).records.length, 0);
  const [remaining] = await conn.query<mysql.RowDataPacket[]>('SELECT * FROM idea ORDER BY id');
  assert.deepEqual(remaining, originals);
  const [payments] = await conn.query<mysql.RowDataPacket[]>('SELECT COUNT(*) AS count FROM payment');
  assert.equal(payments[0].count, 0);
  // Physical cleanup: every logical dependency, rollback and unrelated rows.
  const insert = async (sql: string, values: (string | number | null)[] = []) => (await conn.execute<mysql.ResultSetHeader>(sql, values))[0].insertId;
  const parent = await insert("INSERT INTO passport (provider,providerId,accessToken,title) VALUES ('quantum-demo','maintenance-test','token','Test')");
  const student = await insert("INSERT INTO user (passportId,title,description) VALUES (?, 'Test','')", [parent]);
  const badIdea = await insert("INSERT INTO idea (title,description,image) VALUES ('Blank', '', '   ')");
  const badProject = await insert("INSERT INTO project (passportId,placeId,ideaId,title,description,image) VALUES (?,575,?,'Dependent','','cover')", [parent, badIdea]);
  const badMeet = await insert("INSERT INTO meet (passportId,placeId,projectId) VALUES (?,575,?)", [parent, badProject]);
  await insert('INSERT INTO projectUser (projectId,userId) VALUES (?,?)', [badProject, student]);
  await insert('INSERT INTO meetUser (meetId,userId) VALUES (?,?)', [badMeet, student]);
  await insert('INSERT INTO ideaUser (ideaId,userId) VALUES (?,?)', [badIdea, student]);
  await insert("INSERT INTO ideaPhoto (id,ideaId,position,photoData) VALUES ('cleanup-photo',?,0, '{}')", [badIdea]);
  await insert("INSERT INTO demoSeedRecord (seedKey,entityType,entityKey,recordId) VALUES ('cleanup-test','idea','blank',?)", [badIdea]);
  for (const [type, id] of [['idea', badIdea], ['project', badProject], ['meet', badMeet]] as const) await insert("INSERT INTO payment (passportId,userId,provider,status,amount,currency,targetType,targetId) VALUES (?,?,'yookassa','pending',100,'RUB',?,?)", [parent, student, type, id]);
  await conn.beginTransaction();
  const beforeCleanup = await DemoMaintenanceService.inspect(conn);
  const manifest = DemoMaintenanceService.manifest(beforeCleanup, database);
  const removals = DemoMaintenanceService.cleanupRows(beforeCleanup, manifest);
  assert.equal(removals.payment.length, 3);
  await DemoMaintenanceService.cleanup(conn, removals);
  await conn.rollback();
  assert.deepEqual(await DemoMaintenanceService.inspect(conn), beforeCleanup);
  await conn.beginTransaction();
  await DemoMaintenanceService.cleanup(conn, DemoMaintenanceService.cleanupRows(await DemoMaintenanceService.inspect(conn), manifest));
  await conn.commit();
  const afterCleanup = await DemoMaintenanceService.inspect(conn);
  assert.equal(DemoMaintenanceService.cleanupRows(afterCleanup, manifest).idea.length, 0);
  const [kept] = await conn.query<mysql.RowDataPacket[]>('SELECT * FROM idea ORDER BY id');
  assert.deepEqual(kept, originals);
  await conn.execute('INSERT INTO idea (id,title,description,image) VALUES (?, ?, ?, ?)', [badIdea, 'Reused ID', '', 'cover']);
  assert.throws(() => DemoMaintenanceService.cleanupRows({ ...afterCleanup, idea: [...afterCleanup.idea, { id: badIdea, image: 'cover' }] }, manifest), /changed/);
  // Three copies merge by keys; project and membership IDs remain unchanged.
  for (const key of ['boat', 'robot', 'lantern']) {
    const target = await insert('INSERT INTO idea (title,description,image,catalogId) VALUES (?,?,?,?)', [key, '', 'cover', `demo-${DEMO_SEED_KEY}-${key}`]);
    const source = await insert('INSERT INTO idea (title,description,image,catalogId) VALUES (?,?,?,?)', [key, '', 'cover', `${personalSeedKey}-${key}`]);
    const project = await insert("INSERT INTO project (passportId,placeId,ideaId,title,description,image) VALUES (?,575,?,'Personal','','cover')", [parent, source]);
    const membership = await insert('INSERT INTO projectUser (projectId,userId) VALUES (?,?)', [project, student]);
    const meeting = await insert('INSERT INTO meet (passportId,placeId,projectId) VALUES (?,575,?)', [parent, project]);
    const attendance = await insert('INSERT INTO meetUser (meetId,userId) VALUES (?,?)', [meeting, student]);
    await insert('INSERT INTO ideaUser (ideaId,userId) VALUES (?,?)', [target, student]);
    await insert('INSERT INTO ideaUser (ideaId,userId) VALUES (?,?)', [source, student]);
    await insert('INSERT INTO ideaUser (ideaId,userId) VALUES (?,?)', [source, student + 1]);
    for (const [id, ideaId, url] of [[`${key}-target`, target, 'same'], [`${key}-duplicate`, source, 'same'], [`${key}-new`, source, 'different']] as const) await insert('INSERT INTO ideaPhoto (id,ideaId,position,photoData) VALUES (?,?,0,?)', [id, ideaId, JSON.stringify({ url })]);
    const payment = await insert("INSERT INTO payment (passportId,userId,provider,status,amount,currency,targetType,targetId) VALUES (?,?,'yookassa','pending',100,'RUB','idea',?)", [parent, student, source]);
    await conn.beginTransaction();
    await DemoMaintenanceService.merge(conn, await DemoMaintenanceService.inspect(conn));
    await conn.commit();
    const [result] = await conn.query<mysql.RowDataPacket[]>('SELECT ideaId FROM project WHERE id=?', [project]);
    assert.equal(result[0].ideaId, target);
    const [users] = await conn.query<mysql.RowDataPacket[]>('SELECT id FROM projectUser WHERE projectId=?', [project]);
    assert.equal(users[0].id, membership);
    const snapshot = await DemoMaintenanceService.inspect(conn);
    assert.equal(snapshot.meet.find(row => row.id === meeting)?.projectId, project);
    assert.equal(snapshot.meetUser.find(row => row.id === attendance)?.meetId, meeting);
    assert.equal(snapshot.ideaUser.filter(row => row.ideaId === target).length, 2);
    assert.equal(snapshot.idea.find(row => row.id === target)?.userCount, 2);
    assert.equal(snapshot.ideaPhoto.filter(row => row.ideaId === target).length, 2);
    assert.equal(snapshot.payment.find(row => row.id === payment)?.targetId, target);
    assert.equal(DemoMaintenanceService.mergePairs(snapshot).length, 0);
  }
  await insert("INSERT INTO passport (id,provider,providerId,accessToken,title) VALUES (42,'quantum-demo','dmitry-test','token','Дмитрий А.')");
  await insert("INSERT INTO user (id,passportId,title,description) VALUES (1,42,'Test','')");
  await insert("INSERT INTO place (id,address,latitude,longitude) VALUES (575,'Fictional','55.75','37.62')");
  await insert("INSERT INTO placePassport (passportId,placeId,role) VALUES (42,575,'admin')");
  for (let day = 0; day < 7; day++) await insert("INSERT INTO placeSchedule (placeId,weekday,enabled,startTime,endTime) VALUES (575,?,1,'09:00','20:00')", [day]);
  await conn.beginTransaction();
  assert.equal((await PersonalDemoService.run(conn, true)).records, 69);
  await conn.commit();
  const personalBefore = await DemoMaintenanceService.inspect(conn);
  await conn.beginTransaction();
  assert.equal((await PersonalDemoService.run(conn, true)).alreadyPresent, true);
  await conn.commit();
  assert.deepEqual(await DemoMaintenanceService.inspect(conn), personalBefore);
  assert.equal(DemoMaintenanceService.mergePairs(personalBefore).length, 0);
  // Exercise production SQL with actual tied dates, popularity and distances.
  await conn.execute("UPDATE idea SET createdAt='2030-01-01 12:00:00', userCount=5");
  const [allIdeaRows] = await conn.query<mysql.RowDataPacket[]>('SELECT id FROM idea ORDER BY id DESC');
  const expectedOrder = allIdeaRows.map(row => row.id);
  const originalQuery = db.query;
  db.query = async <T = mysql.RowDataPacket>(sql: string, params?: unknown[]): Promise<T[]> => (await conn.query<mysql.RowDataPacket[]>(sql, params))[0] as T[];
  try {
    for (const sort of ['new', 'popular', 'nearby'] as const) assert.deepEqual((await IdeaRepository.findAll({ sort })).map(row => row.id), expectedOrder);
    const nearestIds = personalBefore.idea.filter(row => typeof row.catalogId === 'string' && row.catalogId.startsWith(`demo-${DEMO_SEED_KEY}-`)).map(row => Number(row.id)).sort((a, b) => b - a);
    const nearby = (await IdeaRepository.findAll({ sort: 'nearby', latitude: 55.75, longitude: 37.62 })).map(row => row.id);
    assert.deepEqual(nearby, [...nearestIds, ...expectedOrder.filter(id => !nearestIds.includes(id))]);
  } finally { db.query = originalQuery; await db.close(); }
  console.log('Isolated demo database: cleanup and import rollback, complete dependencies, three merges, personal repeat, stable extension IDs, schedules, protected removal and catalog preservation passed.');
} finally {
  await conn.rollback();
  await conn.query(`DROP DATABASE IF EXISTS ${database}`);
  conn.release();
  await pool.end();
}
