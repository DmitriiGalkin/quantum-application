  // Exercise the real HTTP router, auth middleware and public response projection.
  process.env.ROBOKASSA_LOGIN = 'rental-test'; process.env.ROBOKASSA_PASSWORD1 = 'test'; process.env.ROBOKASSA_PASSWORD2 = 'test';
  process.env.GIGA_CREDENTIALS = 'test'; process.env.YANDEX_STRATEGY_CLIENT_ID = 'test'; process.env.YANDEX_STRATEGY_CLIENT_SECRET = 'test';
