  await RentalService.changeStatus(confirmed[0].id, confirmed[0].passportId, 'cancelled', null);
  await assert.rejects(RentalService.changeStatus(confirmed[0].id, 30, 'confirmed', null, 1), error => (error as { status: number }).status === 409);
  const rejected = await RentalService.create(10, input('16:00', '17:00'));
  await assert.rejects(RentalService.changeStatus(rejected, 30, 'rejected', '', 1), error => (error as { status: number }).status === 400);
  await RentalService.changeStatus(rejected, 30, 'rejected', 'Unavailable', 1);
  assert.equal((await RentalService.list(10)).find(row => row.id === rejected)?.rejectionReason, 'Unavailable');
  const optional = { ...roomInput, title: 'Other hall', capacity: null, hourlyRate: null, photoUrls: [] };
  await rooms.update(2, 1, 30, optional);
