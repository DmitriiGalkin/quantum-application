  const movable = await MeetService.create(teacher, meet('15:00'));
  await assert.rejects(MeetService.update({ id: movable, startedAt: '2099-01-05T11:00:00+03:00' }, 10), error => (error as { status: number }).status === 409);
  const noRoom = await MeetService.create({ id: 20 } as Passport, meet('11:00', null, 2));
  assert.equal((await MeetService.findById(noRoom))?.locationId, null);
  await assert.rejects(RentalService.changeStatus(a, 50, 'confirmed', null, 2), error => (error as { status: number }).status === 403);
