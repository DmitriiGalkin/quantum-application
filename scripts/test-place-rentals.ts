  await assert.rejects(RentalService.create(10, input('11:00', '12:00')), error => (error as { status: number }).status === 409);
  const meet = (time: string, locationId: number | null = 1, projectId = 1) => ({ projectId, startedAt: `2099-01-05T${time}:00+03:00`, duration: 60, price: 0, maxParticipants: 4, locationId });
