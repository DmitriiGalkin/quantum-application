
import { convertToProjectObject, convertToUserObject } from '../services/helper.js';
import assistant from '../assistant.js';

const SYSTEM_PROMPT = `Роль и экспертиза
Ты — ассистент образовательного проекта для детей.
Твоя задача — помогать родителям развивать креативность и интерес к обучению через индивидуальные образовательные проекты.
Ты общаешься на русском языке, как заботливый педагог, который вдохновляет, но не обещает невозможного.

Основная задача
Получить от родителя информацию о ребенке: возраст, имя, 2-3 увлечения (ОБЯЗАТЕЛЬНО).
Нужно, чтобы родитель сказал конкретное имя ребенка и конкретные увлечения.

Правила форматирования ответа
      - Никогда не повторяй слова пользователя.
      - Не используй фразы вроде "Вы сказали", "Вы написали", "Вот данные", "Вот что известно".
      - Не придумывай имена.
      - Не придумывай увлечения.
      - Не придумывай возраст.
      - Если информации мало, задавай вопросы для уточнения.
      - Ответ должен быть только по существу задачи.
      - Ответ должен начинаться с заглавной буквы.
      
Пошаговый процесс (ВСЕГДА СЛЕДУЙ ПОРЯДКУ ДЕЙСТВИЙ)
1. Проанализируй, что родитель уже сказал о ребенке.
2. Если информация НЕСФОРМИРОВАНА (неясна или слишком общая):
   - Задай 1–3 уточняющих вопросов (например: «Что его особенно увлекает?», «Какой возраст у ребенка?», "Как зовут ребенка?", «Есть ли у него уже какие-то материалы или интересы?»).
3. Если информация сформирована, твой ответ должен состоять из ДВУХ частей:
Первая: Дружелюбное и вдохновляющее благодарность родителю за предоставленную информацию.
Вторая: Структурированный ВАЛИДНЫЙ объект JSON с ключами status, title, description, age. Все поля должны быть заполнены. Этот блок должен быть СТРОГО в конце и отделен от основного текста. Никаких символов после этого JSON.
Пример:
Благодарим за доверие! Вот что я узнал о вашем ребенке { "status": "не подтверждено", "title": "Иван", "description": "Увлекается рисованием, игрой на скрипке и иногда играет в лего", "age": "12" }
ВНИМАНИЕ: JSON должен быть строго последним элементом в твоем ответе. После закрывающей скобки } не должно быть никакого текста, примечаний или пояснений.
Избегай фраз типа "Вот данные о вашем ребенке".
4. Пользователь явно должен подтвердить представленную информацию, и только после status становится "подтверждено"
`;

//Reasoning and Acting
export async function userAssistantAnswer({ messages }) {
  try {
    const payload = {
      messages: [
        {
          role: 'system',
          content: SYSTEM_PROMPT,
        },
        ...messages.map(m => ({ role: m.role, content: m.content })),
      ],
    };

    console.log(payload);
    // 3. Отправка запроса к API
    const resp = await assistant.chat(payload);

    // 4. Проверка структуры ответа от API
    if (!resp || !resp.choices || resp.choices.length === 0) {
      throw new Error('Ошибка API: Получен пустой или некорректный ответ от сервера.');
    }

    const parsedData = resp.choices[0]?.message.content;
    console.log('Content: ', parsedData);

    // 1. Разделяем текст и JSON
    // Ищем начало блока кода ``` или просто первую скобку {
    const jsonStartIndex = parsedData.indexOf('{');
    // console.log('jsonStartIndex: ', jsonStartIndex);

    const userMessage =
      jsonStartIndex !== -1 ? parsedData.slice(0, jsonStartIndex).trim() : parsedData; // Текст для пользователя
    const jsonString = jsonStartIndex !== -1 ? parsedData.slice(jsonStartIndex).trim() : null; // Строка JSON

    // 2. Парсим JSON
    //console.log('Agent: user');
    //console.log(userMessage, 'userMessage');
    //console.log(jsonString, 'jsonString');

    const metadata = jsonString
      ? JSON.stringify({
          target: 'user',
          data: convertToUserObject(jsonString),
        })
      : null;
    //console.log(metadata, 'metadata');

    return {
      content: userMessage,
      metadata: metadata,
    };
  } catch (error) {
    // --- БЛОК ЛОГИРОВАНИЯ И ВОЗВРАТА ОШИБКИ ---

    // Логируем техническую ошибку для разработчика
    console.error('Ошибка в generateAssistantAnswer:', error);

    // Возвращаем объект в СТРОГОМ формате, который ожидает ваш фронтенд/контроллер.
    // Это предотвращает падение всего приложения на клиенте.
    return {
      status: 'error', // Добавляем статус ошибки
      message:
        'Упс! Кажется, наш помощник немного устал и не смог ответить прямо сейчас. Пожалуйста, попробуйте задать вопрос позже.',
      idea: {
        title: 'Ошибка сервиса',
        description: 'Временные технические неполадки на стороне сервера.',
      },
    };
  }
}
